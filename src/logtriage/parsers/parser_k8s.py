"""
Kubernetes API Server Audit Log parser.

Input: NDJSON (one audit event per line), a JSON array or an EventList
({"kind": "EventList", "items": [...]}); lines may carry a prefix such as
grep's `audit.log:` (json_input reads all of these).
Generated by the Kubernetes API server with audit policy enabled.

Reference: https://kubernetes.io/docs/tasks/debug/debug-cluster/audit/

Key fields mapped:
  requestReceivedTimestamp / stageTimestamp → timestamp
  sourceIPs[0]               → ip_address
  userAgent                  → user_agent
  verb                       → http_method (get→GET, create→POST, delete→DELETE, etc.)
  objectRef.resource + namespace → path
  responseStatus.code        → status_code
  user.username              → user_principal_name
  annotations["authorization.k8s.io/decision"] → failure_reason if "forbid"
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Any

from logtriage.parsers import json_input
from logtriage.parsers.base_parser import BaseParser
from logtriage.models import LogEvent, LogFormat

logger = logging.getLogger(__name__)

_VERB_METHOD: dict[str, str] = {
    "get": "GET",
    "list": "GET",
    "watch": "GET",
    "create": "POST",
    "update": "PUT",
    "patch": "PATCH",
    "delete": "DELETE",
    "deletecollection": "DELETE",
    "exec": "POST",
    "portforward": "POST",
    "proxy": "GET",
    "connect": "CONNECT",
    "bind": "POST",
    "escalate": "POST",
    "impersonate": "POST",
}

# Subresources that indicate high-risk activity
_HIGH_RISK_SUBRESOURCES = {"exec", "portforward", "attach", "log", "proxy"}

# Resources that are sensitive
_SENSITIVE_RESOURCES = {
    "secrets", "serviceaccounts", "clusterrolebindings", "rolebindings",
    "clusterroles", "roles", "tokenreviews", "subjectaccessreviews",
}


# Kubernetes' own components: their constant secret reads, bindings and pod creation
# (DaemonSets) are the cluster working, not an actor to investigate.
_CONTROL_PLANE_USERS = frozenset({
    "system:apiserver", "system:kube-controller-manager", "system:kube-scheduler", "system:kube-proxy",
})
_CONTROL_PLANE_PREFIXES = ("system:node:", "system:serviceaccount:kube-system:")
_HEALTH_PATHS = ("/healthz", "/livez", "/readyz", "/version", "/openid/", "/.well-known/")


def _is_control_plane(username: str | None) -> bool:
    return bool(username) and (username in _CONTROL_PLANE_USERS or username.startswith(_CONTROL_PLANE_PREFIXES))


def _is_privileged_pod(spec: dict[str, Any]) -> bool:
    containers = (spec.get("containers") or []) + (spec.get("initContainers") or [])
    return bool(
        any(isinstance(c, dict) and (c.get("securityContext") or {}).get("privileged") for c in containers)
        or spec.get("hostPID") or spec.get("hostNetwork") or spec.get("hostIPC")
        or any(isinstance(v, dict) and (v.get("hostPath") or {}).get("path") == "/" for v in spec.get("volumes") or [])
    )


def _signals(raw: dict[str, Any], username: str | None, status_code: int | None) -> list[str]:
    """What this request means for security — read from the audit record itself
    (roleRef and pod spec are only here). Successful requests only; a refused one
    is scored by its status code. The free analyzer's Kubernetes checks match these
    (marketing/src/lib/analyzer/adapters/cloud.mjs, k8sEvent)."""
    if status_code is not None and status_code >= 400:
        return []
    verb = str(raw.get("verb") or "").lower()
    ref: dict[str, Any] = raw.get("objectRef") or {}
    resource, subresource, namespace = ref.get("resource"), ref.get("subresource"), ref.get("namespace")
    system = _is_control_plane(username)

    if username == "system:anonymous":
        uri = str(raw.get("requestURI") or "")
        return [] if uri.startswith(_HEALTH_PATHS) else ["k8s_anonymous_allowed"]
    if resource in ("rolebindings", "clusterrolebindings") and verb in ("create", "update", "patch") and not system:
        body = raw.get("requestObject") or raw.get("responseObject") or {}
        role = (body.get("roleRef") or {}).get("name") if isinstance(body, dict) else None
        if role == "cluster-admin":
            return ["k8s_cluster_admin_binding"]
        return ["k8s_cluster_role_binding" if resource == "clusterrolebindings" else "k8s_role_binding"]
    if resource == "pods" and subresource in ("exec", "attach", "portforward"):
        return ["k8s_exec"]
    if resource == "pods" and verb == "create" and not subresource and not system:
        spec = (raw.get("requestObject") or {}).get("spec") or {}
        return ["k8s_privileged_pod"] if isinstance(spec, dict) and _is_privileged_pod(spec) else []
    if resource == "secrets" and verb in ("get", "list", "watch") and not system:
        if not namespace or namespace == "kube-system":
            return ["k8s_secrets_cluster_wide"]
        return ["k8s_secret_read"]
    return []


def _ts(raw: str | None) -> datetime:
    if not raw:
        return datetime.now(timezone.utc)
    try:
        return datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except (ValueError, AttributeError):
        return datetime.now(timezone.utc)


def _build_path(
    obj_ref: dict[str, Any] | None, verb: str | None, subresource: str | None, request_uri: str | None = None,
) -> str:
    if not obj_ref:
        # Non-resource requests (/metrics, /healthz, /version, /apis discovery) have no objectRef
        uri = (request_uri or "").split("?", 1)[0]
        return uri if uri.startswith("/") else f"/k8s/{verb or 'unknown'}"
    ns = obj_ref.get("namespace", "")
    resource = obj_ref.get("resource", "unknown")
    name = obj_ref.get("name", "")
    parts = ["/k8s"]
    if ns:
        parts += ["namespaces", ns]
    parts.append(resource)
    if name:
        parts.append(name)
    if subresource:
        parts.append(subresource)
    return "/".join(parts)


def _parse_event(raw: dict[str, Any]) -> LogEvent | None:
    try:
        verb: str | None = raw.get("verb")
        obj_ref: dict[str, Any] | None = raw.get("objectRef")
        user: dict[str, Any] = raw.get("user") or {}
        source_ips: list[str] = raw.get("sourceIPs") or []
        response: dict[str, Any] = raw.get("responseStatus") or {}
        annotations: dict[str, str] = raw.get("annotations") or {}
        subresource: str | None = obj_ref.get("subresource") if obj_ref else None

        ts_raw = raw.get("requestReceivedTimestamp") or raw.get("stageTimestamp")
        status_code: int | None = response.get("code")

        # Forbidden by RBAC
        authz_decision = annotations.get("authorization.k8s.io/decision", "")
        failure_reason = None
        if authz_decision == "forbid":
            failure_reason = "RBAC: access forbidden"
            if not status_code:
                status_code = 403
        elif status_code and status_code >= 400:
            failure_reason = response.get("message") or response.get("reason")

        username = user.get("username")
        if not username:
            username = user.get("extra", {}).get("username", [None])[0] if isinstance(user.get("extra"), dict) else None

        path = _build_path(obj_ref, verb, subresource, raw.get("requestURI"))
        http_method = _VERB_METHOD.get((verb or "").lower(), "GET")

        resource_name = obj_ref.get("resource") if obj_ref else None
        resource_display = f"k8s/{resource_name}" if resource_name else "Kubernetes API Server"

        # `kubectl --as` and access proxies (Rancher, Teleport) act as another identity:
        # the request ran with the impersonated user's rights, so that is who it is attributed to.
        impersonated = raw.get("impersonatedUser") or {}
        if isinstance(impersonated, dict) and impersonated.get("username"):
            username = impersonated["username"]

        return LogEvent(
            source_format=LogFormat.K8S_AUDIT,
            timestamp=_ts(ts_raw),
            ip_address=source_ips[0] if source_ips else None,
            user_agent=raw.get("userAgent"),
            http_method=http_method,
            path=path,
            status_code=status_code,
            user_principal_name=username,
            resource_display_name=resource_display,
            failure_reason=failure_reason,
            signals=_signals(raw, username, status_code),
        )
    except Exception as exc:
        logger.debug("Skipping malformed K8s audit event: %s", exc)
        return None


# A request is logged once per stage; RequestReceived and ResponseStarted repeat
# what the ResponseComplete (or Panic) record of the same request says.
_INTERMEDIATE_STAGES = frozenset({"RequestReceived", "ResponseStarted"})


def _is_audit_event(obj: dict[str, Any]) -> bool:
    if str(obj.get("apiVersion", "")).startswith("audit.k8s.io"):
        return True
    return (
        ("verb" in obj and "auditID" in obj and ("objectRef" in obj or "requestURI" in obj))
        or ("objectRef" in obj and "requestReceivedTimestamp" in obj)
        or ("objectRef" in obj and "verb" in obj and "user" in obj and "sourceIPs" in obj)
    )


def parse_k8s_audit(content: str) -> list[LogEvent]:
    """Parse a Kubernetes audit log (NDJSON, a JSON array or an EventList, also
    with a prefix on each line such as grep's `audit.log:`) into LogEvents."""
    records = [
        r for r in json_input.records(content, ("items",))
        if r.get("stage") not in _INTERMEDIATE_STAGES
    ]
    events = [_parse_event(r) for r in records]
    result = [e for e in events if e is not None]
    logger.info("K8s audit parser: %d/%d events parsed", len(result), len(records))
    return result


class K8sAuditParser(BaseParser):
    format_name = "k8s_audit"

    @classmethod
    def can_parse(cls, content: str, filename: str) -> bool:
        head = json_input.sample(content, ("items",))
        return bool(head) and sum(_is_audit_event(r) for r in head) * 2 > len(head)

    @classmethod
    def parse(cls, content: str, filename: str = "") -> list[LogEvent]:
        return parse_k8s_audit(content)
